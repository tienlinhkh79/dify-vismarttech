import type {
  OmnichannelRichReplyButton,
  OmnichannelRichReplyCard,
  OmnichannelRichReplyPayload,
} from './types'

function normalizeRawText(text: string): string {
  let value = text.trim()
  value = value.replace(/^\s*text\s*:\s*/i, '')
  if (value.startsWith('```') && value.endsWith('```')) {
    value = value.replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/, '').trim()
  }
  return value
}

function parseButton(raw: unknown): OmnichannelRichReplyButton | null {
  if (!raw || typeof raw !== 'object')
    return null
  const item = raw as Record<string, unknown>
  const title = String(item.title || '').trim()
  if (!title)
    return null
  const action = item.action === 'url' ? 'url' : 'postback'
  const button: OmnichannelRichReplyButton = { title, action }
  const url = String(item.url || '').trim()
  const payload = String(item.payload || '').trim()
  const imageUrl = String(item.image_url || '').trim()
  if (action === 'url' && url)
    button.url = url
  if (action === 'postback')
    button.payload = payload || slugLabel(title)
  if (imageUrl)
    button.image_url = imageUrl
  return button
}

function parseCard(raw: unknown): OmnichannelRichReplyCard | null {
  if (!raw || typeof raw !== 'object')
    return null
  const item = raw as Record<string, unknown>
  const title = String(item.title || '').trim()
  if (!title)
    return null
  const card: OmnichannelRichReplyCard = { title }
  const subtitle = String(item.subtitle || '').trim()
  const imageUrl = String(item.image_url || item.image || '').trim()
  const defaultUrl = String(item.default_url || '').trim()
  if (subtitle)
    card.subtitle = subtitle
  if (imageUrl)
    card.image_url = imageUrl
  if (defaultUrl)
    card.default_url = defaultUrl
  const rawButtons = item.buttons
  if (Array.isArray(rawButtons)) {
    const buttons = rawButtons
      .map(parseButton)
      .filter((button): button is OmnichannelRichReplyButton => button !== null)
    if (buttons.length)
      card.buttons = buttons
  }
  return card
}

function parseActions(data: Record<string, unknown>): OmnichannelRichReplyPayload | null {
  const text = String(data.text || '').trim()
  const rawButtons = Array.isArray(data.buttons) ? data.buttons : []
  const buttons = rawButtons
    .map(parseButton)
    .filter((button): button is OmnichannelRichReplyButton => button !== null)
  if (!text && !buttons.length)
    return null
  return {
    type: 'actions',
    text: text || '',
    buttons,
  }
}

function parseCards(data: Record<string, unknown>): OmnichannelRichReplyPayload | null {
  const rawCards = data.cards
  if (!Array.isArray(rawCards) || !rawCards.length)
    return null
  const cards = rawCards
    .map(parseCard)
    .filter((card): card is OmnichannelRichReplyCard => card !== null)
  if (!cards.length)
    return null
  const payload: OmnichannelRichReplyPayload = { type: 'cards', cards }
  const text = String(data.text || '').trim()
  if (text)
    payload.text = text
  const rawButtons = data.buttons
  if (Array.isArray(rawButtons)) {
    const buttons = rawButtons
      .map(parseButton)
      .filter((button): button is OmnichannelRichReplyButton => button !== null)
    if (buttons.length)
      payload.buttons = buttons
  }
  return payload
}

function parseQuickReplies(data: Record<string, unknown>): OmnichannelRichReplyPayload | null {
  const text = String(data.text || '').trim()
  const rawQuick = data.quick_replies
  if (!Array.isArray(rawQuick))
    return null
  const buttons = buttonsFromQuickReplies(rawQuick)
  if (!text && !buttons.length)
    return null
  return { type: 'actions', text, buttons }
}

export function slugLabel(label: string): string {
  const folded = label.normalize('NFKD').replace(/\p{M}/gu, '')
  const value = folded
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '')
    .slice(0, 40)
  return value || label
}

/** Pre-NFKD slug kept for matching payloads generated by older UI builds. */
export function legacySlugLabel(label: string): string {
  return label
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '')
    .slice(0, 40) || label
}

export function isDerivedSlugPayload(title: string, payload: string): boolean {
  const normalizedPayload = payload.trim()
  if (!normalizedPayload)
    return false
  return normalizedPayload === slugLabel(title) || normalizedPayload === legacySlugLabel(title)
}

function buttonsFromQuickReplies(rawQuick: unknown[]): OmnichannelRichReplyButton[] {
  const buttons: OmnichannelRichReplyButton[] = []
  for (const raw of rawQuick.slice(0, 4)) {
    if (typeof raw === 'string') {
      const title = raw.trim()
      if (!title)
        continue
      buttons.push({
        title,
        action: 'postback',
        payload: slugLabel(title),
      })
      continue
    }
    if (!raw || typeof raw !== 'object')
      continue
    const item = raw as Record<string, unknown>
    const title = String(item.title || '').trim()
    if (!title)
      continue
    buttons.push({
      title,
      action: 'postback',
      payload: String(item.payload || title).trim(),
      ...(String(item.image_url || '').trim()
        ? { image_url: String(item.image_url).trim() }
        : {}),
    })
  }
  return buttons
}

function parseLlmStructuredOutput(data: Record<string, unknown>): OmnichannelRichReplyPayload | null {
  const aiReply = String(data.ai_reply || data.aireply || '').trim()
  const quickRaw = data.quick_replies ?? data.quickreplies
  const quickList = Array.isArray(quickRaw) ? quickRaw : []
  const buttons = buttonsFromQuickReplies(quickList)

  const products = data.products
  if (Array.isArray(products) && products.length > 0) {
    const cardsPayload = parseCards({
      type: 'cards',
      text: aiReply,
      cards: products.map((item) => {
        if (!item || typeof item !== 'object')
          return null
        const product = item as Record<string, unknown>
        const title = String(product.product_name || product.title || product.name || '').trim()
        if (!title)
          return null
        const card: OmnichannelRichReplyCard = { title }
        const subtitle = String(product.price || product.subtitle || '').trim()
        const imageUrl = String(product.image_url || product.image || '').trim()
        const detailUrl = String(product.detail_url || product.url || product.link || '').trim()
        if (subtitle)
          card.subtitle = subtitle
        if (imageUrl)
          card.image_url = imageUrl
        if (detailUrl) {
          card.default_url = detailUrl
          card.buttons = [{ title: 'Xem chi tiết', action: 'url', url: detailUrl }]
        }
        return card
      }).filter((card): card is OmnichannelRichReplyCard => card !== null),
      buttons,
    })
    if (cardsPayload)
      return cardsPayload
  }

  if (!aiReply && !buttons.length)
    return null

  return {
    type: 'actions',
    text: aiReply,
    buttons: buttons.length
      ? buttons
      : [
          { title: 'Tư vấn thêm', action: 'postback', payload: slugLabel('Tư vấn thêm') },
          { title: 'Liên hệ', action: 'postback', payload: slugLabel('Liên hệ') },
        ],
  }
}

function tryParseJsonRecord(raw: string): Record<string, unknown> | null {
  const normalized = normalizeRawText(raw)
  if (!normalized.startsWith('{'))
    return null
  try {
    const data = JSON.parse(normalized)
    return data && typeof data === 'object' ? data as Record<string, unknown> : null
  }
  catch {
    const start = normalized.indexOf('{')
    if (start < 0)
      return null
    for (let end = normalized.length; end > start; end -= 1) {
      const chunk = normalized.slice(start, end)
      if (!chunk.endsWith('}'))
        continue
      try {
        const data = JSON.parse(chunk)
        if (data && typeof data === 'object')
          return data as Record<string, unknown>
      }
      catch {
        // keep scanning
      }
    }
    return null
  }
}

function parseRecord(record: Record<string, unknown>): OmnichannelRichReplyPayload | null {
  const replyType = String(record.type || '').trim().toLowerCase()
  if (replyType === 'cards')
    return parseCards(record)
  if (replyType === 'actions') {
    const actions = parseActions(record)
    if (!actions)
      return null
    const inner = tryParseJsonRecord(actions.text)
    if (inner && (inner.ai_reply || inner.quick_replies || inner.quickreplies))
      return parseLlmStructuredOutput(inner) || actions
    return actions
  }
  if (replyType === 'quick_replies')
    return parseQuickReplies(record)
  if (record.ai_reply || record.aireply || record.quick_replies || record.quickreplies || record.products)
    return parseLlmStructuredOutput(record)
  return null
}

export function parseOmnichannelRichReply(raw: unknown): OmnichannelRichReplyPayload | null {
  if (typeof raw !== 'string' || !raw.trim())
    return null

  const record = tryParseJsonRecord(raw)
  if (!record)
    return null

  return parseRecord(record)
}
